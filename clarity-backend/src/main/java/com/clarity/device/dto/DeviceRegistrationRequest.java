package com.clarity.device.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@Schema(description = "Device registration or heartbeat request payload")
public class DeviceRegistrationRequest {

    @NotBlank(message = "installationId must not be blank")
    @Size(max = 255, message = "installationId must not exceed 255 characters")
    @Schema(description = "Unique device installation identifier generated by client app", example = "d9f8c12a-89a1-432a-bc91-239104812f81")
    private String installationId;

    @Size(max = 50, message = "platform must not exceed 50 characters")
    @Schema(description = "Operating system platform (e.g. android, ios, web)", example = "android")
    private String platform;

    @Size(max = 50, message = "appVersion must not exceed 50 characters")
    @Schema(description = "Semantic version of the installed client application", example = "1.0.0")
    private String appVersion;

    @Size(max = 255, message = "deviceName must not exceed 255 characters")
    @Schema(description = "Device brand or model name", example = "Samsung Galaxy S24")
    private String deviceName;
}
